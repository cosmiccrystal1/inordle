from pathlib import Path
import json,itertools,re
p=Path(__file__).resolve().parent
# Human-selected, ordinary words seed candidates; dictionary verifies solvability.
seeds='great planet bridge garden mountain blanket friendship sunflower triangle breakfast notebook butterfly playground adventure celebrate chocolate discovery elephant fireplace grateful happiness important journey keyboard language marathon neighbor orchestra painting question rainbow sandwich treasure umbrella vegetable waterfall yesterday blueprint craftsmanship understanding photograph basketball wonderful strawberry dragonfly lighthouse snowflake compass'.split()
words=json.loads((p/'data/words.json').read_text(encoding='utf-8'))
groups={'consonants':set(),'vowels':set()}
for seed in seeds:
 consonants=''.join(c for c in seed if c not in 'aeiou')
 for length in range(2,6):
  groups['consonants'].update(''.join(chars).upper() for chars in itertools.combinations(consonants,length))
 for length in range(3,6):
  groups['vowels'].update(''.join(chars).upper() for chars in itertools.combinations(seed,length) if sum(c in 'aeiou' for c in chars)==1)
for kind,candidates in groups.items():
 accepted=[]
 for trail in sorted(candidates):
  pattern=re.compile('.*'.join(trail.lower()))
  count=0
  for word in words:
   if pattern.search(word):
    count+=1
    if count==4:break
  if count==4:accepted.append(trail)
 groups[kind]=accepted
 for length in (range(2,6) if kind=='consonants' else range(3,6)):
  assert any(len(t)==length for t in accepted),(kind,length)
(p/'trails.js').write_text('// Generated by build-trails.py; each trail has at least four filtered dictionary solutions.\nexport const trails = '+json.dumps(groups,separators=(',',':'))+';\n')
# SQL and JavaScript choose from the same sorted catalog. No dictionary scan per visitor.
sql='-- Generated by build-trails.py. Run after schema.sql and dictionary.sql.\ncreate or replace function public.trail(d date) returns text\nlanguage plpgsql immutable set search_path = \'\' as $$\ndeclare\n n integer := d - date \'1970-01-01\';\n pool text[];\n target integer;\n candidates text[];\nbegin\n'
sql+=' if ((n%12+12)%12)=0 then\n  target := 3+(((floor(n::numeric/12)::integer)%3+3)%3);\n  pool := array['+','.join("'%s'"%t for t in groups['vowels'])+'];\n else\n  target := 2+((n%4+4)%4);\n  pool := array['+','.join("'%s'"%t for t in groups['consonants'])+'];\n end if;\n'
sql+=" select array_agg(t order by t) into candidates from unnest(pool) as t where length(t)=target;\n return candidates[1+((((n::bigint*48271)%2147483647+2147483647)%2147483647)%cardinality(candidates))::integer];\nend $$;\nrevoke all on function public.trail(date) from public, anon, authenticated;\n"
(p/'supabase/trails.sql').write_text(sql)
print({k:len(v) for k,v in groups.items()})
