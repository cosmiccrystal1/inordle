from pathlib import Path
import json,itertools,re
p=Path(__file__).resolve().parent
# Human-selected, ordinary words seed candidates; dictionary verifies solvability.
seeds='great planet bridge garden mountain blanket friendship sunflower triangle breakfast notebook butterfly playground adventure celebrate chocolate discovery elephant fireplace grateful happiness important journey keyboard language marathon neighbor orchestra painting question rainbow sandwich treasure umbrella vegetable waterfall yesterday blueprint craftsmanship understanding photograph basketball wonderful strawberry dragonfly lighthouse snowflake compass'.split()
words=json.loads((p/'data/words.json').read_text(encoding='utf-8'))
groups={'consonants':set(),'vowels':set()}
for seed in seeds:
 consonants=''.join(c for c in seed if c not in 'aeiou')
 for length in range(2,6):
  groups['consonants'].update(''.join(chars).upper() for chars in itertools.combinations(consonants,length))
 for length in range(3,6):
  groups['vowels'].update(''.join(chars).upper() for chars in itertools.combinations(seed,length) if sum(c in 'aeiou' for c in chars)==1)

import sys, math
sys.path.insert(0,str(p/'.build-deps'))
from wordfreq import zipf_frequency
forms=json.loads((p/'data/singular-forms.json').read_text(encoding='utf-8'))
# Only canonical dictionary words count. Plural variants cannot pad the solution minimum.
canonical=sorted({forms.get(w,w) for w in words})
frequencies={w:round(zipf_frequency(w,'en')*100) for w in canonical}
# Require eight attested solutions with Zipf >= 2.5 (roughly 3 per ten million words).
ordered=sorted((w for w in canonical if frequencies[w]>=250),key=lambda w:(-frequencies[w],w))
print('Canonical frequency-attested candidates:',len(ordered),flush=True)
weights={};quality={}
for kind,candidates in groups.items():
 accepted=[]
 for trail in sorted(candidates):
  pattern=re.compile('.*'.join(trail.lower()))
  solutions=[]
  for word in ordered:
   if pattern.search(word):
    solutions.append(word)
    if len(solutions)==8:break
  if len(solutions)<8:continue
  # Average Zipf frequency of the eight most common canonical solutions.
  # Every 1-point rise in Zipf corresponds to a tenfold rise in frequency.
  mean=sum(frequencies[w] for w in solutions)/800
  weight=max(1,min(10000,int(math.floor(10**(mean-2)+0.5))))
  weights[trail]=weight
  quality[trail]={'solutions':solutions,'zipf100':[frequencies[w] for w in solutions],'weight':weight}
  accepted.append(trail)
 groups[kind]=accepted
 for length in (range(2,6) if kind=='consonants' else range(3,6)):
  assert any(len(t)==length for t in accepted),(kind,length)
(p/'trails.js').write_text('// Generated by build-trails.py; at least eight canonical solutions per trail.\nexport const trails = '+json.dumps(groups,separators=(',',':'))+';\nexport const trailWeights = '+json.dumps(weights,separators=(',',':'))+';\n',encoding='utf-8')
(p/'data/trail-quality.json').write_text(json.dumps(quality,separators=(',',':')),encoding='utf-8')
# Small generated SQL seed, rather than scanning the full dictionary for each visitor.
sql="""-- Generated frequency-weighted catalog. Run 01-prepare.sql before updating an existing site.
begin;
create table if not exists public.trail_catalog(
 letters text primary key, weight integer not null check(weight>0)
);
alter table public.trail_catalog enable row level security;
revoke all on public.trail_catalog from anon, authenticated;
"""
sql+='delete from public.trail_catalog;\n'
for start in range(0,len(weights),1000):
 rows=list(weights.items())[start:start+1000]
 sql+='insert into public.trail_catalog(letters,weight) values '+','.join("('%s',%d)"%(t,w) for t,w in rows)+' on conflict(letters) do update set weight=excluded.weight;\n'
sql+="""
create or replace function public.trail_weighted(d date) returns text
language plpgsql stable set search_path = '' as $$
declare
 n integer := d - date '1970-01-01';
 rare boolean := ((n%12+12)%12)=0;
 target integer;
 total bigint;
 ticket bigint;
 seed bigint;
 i integer;
 selected text;
begin
 target := case when rare then 3+(((floor(n::numeric/12)::integer)%3+3)%3) else 2+((n%4+4)%4) end;
 select sum(weight) into total from public.trail_catalog where length(letters)=target and (letters ~ '[AEIOU]')=rare;
 if total is null then raise exception 'Trail catalog is not ready'; end if;
 -- Integer-only deterministic ticket, identical to the browser implementation.
 seed := ((n::bigint%2147483647)+2147483647)%2147483647;
 for i in 1..3 loop seed := (seed*48271)%2147483647; end loop;
 ticket := (seed*total)/2147483647;
 select letters into selected from (
  select letters,sum(weight) over(order by letters collate "C") as cumulative
  from public.trail_catalog where length(letters)=target and (letters ~ '[AEIOU]')=rare
 ) choices where cumulative>ticket order by cumulative limit 1;
 return selected;
end $$;
create or replace function public.trail(d date) returns text
language sql stable set search_path = '' as $$
 select coalesce((select letters from public.daily_puzzles where day=d),public.trail_weighted(d));
$$;
revoke all on function public.trail(date),public.trail_weighted(date) from public, anon, authenticated;
commit;
"""
(p/'supabase/trails.sql').write_text(sql,encoding='utf-8')
print({k:len(v) for k,v in groups.items()})
print('Weight range:',min(weights.values()),max(weights.values()),'SQL bytes:',len(sql.encode()))
