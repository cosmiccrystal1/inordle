import fs from 'node:fs';
import pluralize from 'pluralize';
const words=new Set(JSON.parse(fs.readFileSync('data/words.json','utf8')));
const forms=Object.create(null);
for(const word of words){
 const singular=pluralize.singular(word);
 if(word.length>2 && singular!==word && words.has(singular) && pluralize.plural(singular)===word) forms[word]=singular;
}
// Resolve chains once, so canonicalization is idempotent on both client and server.
for(const word of Object.keys(forms)){
 let canonical=forms[word];const seen=new Set([word]);
 while(forms[canonical]&&!seen.has(canonical)){seen.add(canonical);canonical=forms[canonical];}
 if(seen.has(canonical))delete forms[word];else forms[word]=canonical;
}
for(const [plural,singular] of Object.entries(forms)){if(!words.has(singular)||typeof singular!=='string')throw new Error('Invalid canonical form: '+plural);}
fs.writeFileSync('normalization.js','// Generated by build-normalization.mjs using pluralize (MIT).\nexport const singularForms = '+JSON.stringify(forms)+';\nexport const normalizeWord = word => Object.hasOwn(singularForms,word) ? singularForms[word] : word;\n');
fs.writeFileSync('data/singular-forms.json',JSON.stringify(forms));
fs.mkdirSync('supabase/word-forms',{recursive:true});
let batch='',part=1;
const flush=()=>{if(batch){fs.writeFileSync(`supabase/word-forms/forms-${String(part++).padStart(2,'0')}.sql`,batch);batch='';}};
const entries=Object.entries(forms);
for(let i=0;i<entries.length;i+=1000){const sql='insert into public.word_forms(plural,singular) values '+entries.slice(i,i+1000).map(([a,b])=>`('${a}','${b}')`).join(',')+' on conflict(plural) do update set singular=excluded.singular;\n';if(batch.length+sql.length>200000)flush();batch+=sql;}flush();
fs.copyFileSync('node_modules/pluralize/LICENSE','data/PLURALIZE-LICENSE');
console.log(`${entries.length} plural forms; ${part-1} SQL import files`);
